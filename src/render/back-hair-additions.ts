/** New back-hair options use their saved IDs; legacy options remain untouched. */
export function backHairAdditions(rows: string[], facing: Facing, kind: number) {
  if (kind < 11 || kind > 20) return
  const view: HairView = facing === 'left' ? 'right' : facing
  const art = ADDITIONS[kind]?.[view]
  if (!art) return

  for (const [y, pixels] of art) {
    if (!rows[y] || y > 9) continue
    for (let x = 0; x < Math.min(10, rows[y].length, pixels.length); x++) {
      const color = pixels[x]
      if (color === '.') continue
      // Reserve the full central face, including both open and blinking eyes.
      if ((y === 4 || y === 5) && view !== 'up' &&
        x >= (view === 'down' ? 2 : 4) && x <= 7) continue
      rows[y] = rows[y].slice(0, x) + color + rows[y].slice(x + 1)
    }
  }
}
