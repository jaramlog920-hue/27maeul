// 기존 아이템 ID와 배치 크기를 유지해 저장된 집과 가방에서도 바로 사용한다.
import type { FurnitureArt } from './furniture-art'

type Rect = readonly [string, number, number, number, number]
export function pixels(w: number, h: number, rects: readonly Rect[]): FurnitureArt {
  const rows = Array.from({ length: h * 16 }, () => Array<string>(w * 16).fill('.'))
  for (const [color, x, y, width, height] of rects) {
    if (x < 0 || y < 0 || x + width > w * 16 || y + height > h * 16)
      throw new Error('집 가구 도트가 배치 크기를 벗어났습니다')
    for (let dy = y; dy < y + height; dy++)
      for (let dx = x; dx < x + width; dx++) rows[dy][dx] = color
  }
  return { w, h, rows: rows.map(row => row.join('')) }
}

