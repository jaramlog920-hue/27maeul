const file = 'src/content/people.json'
let text = readFileSync(file, 'utf8')
const json = (s) => JSON.stringify(s)
let changed = 0
const missing = []
for (const [from, to] of Object.entries(MAP)) {
  const needle = `"label": ${json(from)}`
  if (!text.includes(needle)) {
    missing.push(from)
    continue
  }
  changed += text.split(needle).length - 1
  text = text.split(needle).join(`"label": ${json(to)}`)
}
writeFileSync(file, text)
console.log(`바꾼 곳 ${changed}, 못 찾은 것 ${missing.length}`)
for (const m of missing) console.log('  없음:', m)
