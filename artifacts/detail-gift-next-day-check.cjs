const { chromium } = require('C:/Users/wn410/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const out = path.resolve('artifacts/detail-audit/006-gift-next-day')
;(async () => {
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
    const page = await context.newPage()
    page.setDefaultTimeout(15000)
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('dialog', d => void d.accept())
    await page.goto('http://127.0.0.1:4186', { waitUntil: 'domcontentloaded' })
    await page.getByRole('button', { name: '새로 시작하기' }).click()
    await page.getByLabel('이름', { exact: true }).fill('다음날선물검사')
    await page.getByRole('button', { name: '이대로 시작', exact: true }).click()
    await page.waitForFunction(() => !!window.__gd?.store)
    const openTalk = () => page.evaluate(() => window.__gd.store.getState().open({ kind: 'talk', neighborId: 'baker', line: '검사용 대화' }))
    const openBed = () => page.evaluate(() => window.__gd.store.getState().open({ kind: 'review', pieceId: null }))
    const snapshot = () => page.evaluate(async () => {
      const { dailyHeartGain } = await import('/src/engine/game.ts')
      const s = window.__gd.store.getState(), g = s.game
      const button = [...document.querySelectorAll('.talk button')].find(b => b.textContent === '선물하기')
      return { clock: g.clock, grapes: g.inv.grapes ?? 0, basket: g.inv.basket ?? 0, gifted: g.gifted,
        hearts: g.hearts.baker, charm: g.stats.charm, dailyGain: dailyHeartGain(g, 'baker'),
        giftDisabled: button?.disabled ?? null, modal: s.modal }
    })
    const saveReload = async () => {
      await page.evaluate(async () => {
        const { saveGameAsync } = await import('/src/engine/save.ts')
        if (!await saveGameAsync(window.__gd.store.getState().game)) throw new Error('save failed')
      })
      await page.reload({ waitUntil: 'domcontentloaded' })
      await page.getByRole('button', { name: '이어하기', exact: true }).click()
      await page.waitForFunction(() => !!window.__gd?.store)
    }
    const results = []
    for (const flow of [{ name: 'regular-night', day: 20, minute: 1320 }, { name: 'season-end-late-night', day: 40, minute: 1560 }, { name: 'sick-morning', day: 20, minute: 1320, sick: true }]) {
      await page.evaluate(async flow => {
        const { CONTENT } = await import('/src/content/catalog.ts')
        const { legacyGame } = await import('/src/engine/growth-test-support.ts')
        const { heartUp } = await import('/src/engine/game.ts')
        const base = legacyGame(CONTENT)
        const game = heartUp({ ...base, clock: { day: flow.day, minute: flow.minute }, inv: { grapes: 3 },
          hearts: { ...base.hearts, baker: 23 }, gifted: [], scenes: [], needs: { ...base.needs, ...(flow.sick ? { hunger: 100 } : {}) } }, 'baker', 3)
        window.__gd.store.getState().load(game)
        window.__gd.store.getState().setDeck(false)
        window.__gd.store.getState().setJoystick(false)
        window.__gd.store.setState({ clockMs: 0, toast: null, piecePopups: [], copyResult: null })
        window.__gd.store.getState().open({ kind: 'talk', neighborId: 'baker', line: '검사용 대화' })
      }, flow)
      await page.getByRole('button', { name: '선물하기', exact: true }).tap()
      await page.getByRole('button', { name: /포도.* 3$/ }).tap()
      const first = await snapshot()
      assert.equal(first.hearts, 29)
      assert.equal(first.dailyGain, 6)
      assert.equal(first.grapes, 2)
      assert.equal(first.giftDisabled, true)
      await saveReload()
      await openTalk()
      const beforeBed = await snapshot()
      assert.deepEqual(beforeBed.gifted, ['baker'])
      assert.equal(beforeBed.giftDisabled, true)
      await openBed()
      const stayLabel = await page.evaluate(async () => (await import('/src/content/text.ts')).T.ui.stayUp)
      const sleepLabel = await page.evaluate(async () => (await import('/src/content/text.ts')).T.ui.sleep)
      await page.getByRole('button', { name: stayLabel, exact: true }).tap()
      await openTalk()
      const canceled = await snapshot()
      assert.equal(canceled.clock.day, flow.day)
      assert.deepEqual(canceled.gifted, ['baker'])
      assert.equal(canceled.giftDisabled, true)
      await openBed()
      await page.getByRole('button', { name: sleepLabel, exact: true }).tap()
      await page.waitForFunction(day => window.__gd.store.getState().game.clock.day === day, flow.day + 1)
      await openTalk()
      const morning = await snapshot()
      assert.deepEqual(morning.gifted, [])
      assert.equal(morning.dailyGain, 0)
      assert.equal(morning.giftDisabled, false)
      assert.equal(morning.grapes, 2)
      assert.equal(morning.hearts, 29)
      const expectedWake = flow.sick ? 600 : flow.minute >= 1380 ? 480 : 360
      assert.ok(morning.clock.minute >= expectedWake && morning.clock.minute < expectedWake + 5)
      await page.screenshot({ path: path.join(out, `${flow.name}-morning.png`), fullPage: true, animations: 'disabled' })
      await saveReload()
      await openTalk()
      assert.equal((await snapshot()).giftDisabled, false)
      await page.getByRole('button', { name: '선물하기', exact: true }).tap()
      await page.getByRole('button', { name: /포도.* 2$/ }).tap()
      const second = await snapshot()
      assert.equal(second.hearts, 32)
      assert.equal(second.dailyGain, 3)
      assert.equal(second.grapes, 1)
      assert.equal(second.basket, 1)
      assert.deepEqual(second.gifted, ['baker'])
      assert.equal(second.giftDisabled, true)
      await saveReload()
      await openTalk()
      const restored = await snapshot()
      for (const key of ['grapes', 'basket', 'gifted', 'hearts', 'charm', 'dailyGain', 'giftDisabled']) assert.deepEqual(restored[key], second[key])
      await page.screenshot({ path: path.join(out, `${flow.name}-second-gift-restored.png`), fullPage: true, animations: 'disabled' })
      results.push({ flow, first, beforeBed, canceled, morning, second, restored })
      console.log('PASS:', flow.name, 'cancel, sleep, next-day unlock, restored unlock, new reward, restored re-lock')
    }
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(out, 'result.json'), JSON.stringify({ passed: true, results, pageErrors: errors }, null, 2))
    await context.close()
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
